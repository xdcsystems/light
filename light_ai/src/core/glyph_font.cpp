    {
        return ( b & 0xC0u ) == 0x80u;
    }

    uint32_t sanitize_cp( uint32_t cp ) noexcept
    {
        if ( cp >= 0x20u && cp <= 0x7Eu )
            return cp;
        if ( cp >= 0x0410u && cp <= 0x044Fu )
            return cp;
        if ( cp == 0x0401u || cp == 0x0451u )
            return cp;
        return '?';
    }

    int append_lit( char* dst, int cap, int pos, const char* lit ) noexcept
    {
        if ( !lit )
            return pos;
        for ( int i = 0; lit[i] != '\0' && pos < cap - 1; ++i )
            dst[pos++] = lit[i];
        return pos;
    }

    int append_int( char* dst, int cap, int pos, int val ) noexcept
    {
        if ( pos >= cap - 1 )
            return pos;
        int len = pos;
        unsigned int mag = 0;
        if ( val < 0 )
        {
            dst[len++] = '-';
            mag = static_cast<unsigned int>( -( val + 1 ) ) + 1u;
        }
        else
        {
            mag = static_cast<unsigned int>( val );
        }
        char rev[12] {};
        int nd = 0;
        do
        {
            rev[nd++] = static_cast<char>( '0' + ( mag % 10u ) );
            mag /= 10u;
        } while ( mag > 0u && nd < 12 );
        while ( nd > 0 && len < cap - 1 )
            dst[len++] = rev[--nd];
        return len;
    }

    void fill_solid_cell( std::array<uint8_t, glyph_font::kAtlasBytes>& atlas ) noexcept
    {
        for ( int r = 0; r < glyph_font::kCellH; ++r )
        {
            uint8_t* dst = atlas.data() + r * glyph_font::kAtlasW;
            std::fill_n( dst, static_cast<int>( glyph_font::kCellW ), uint8_t { 0xFFu } );
        }
    }

