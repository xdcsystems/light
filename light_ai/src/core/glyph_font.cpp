    bool is_cont( uint8_t b ) noexcept
    {
        return ( b & 0xC0u ) == 0x80u;
    }

    uint32_t sanitize_cp( uint32_t cp ) noexcept
    {
        if ( cp < 0x20u || cp == 0x7Fu )
            return '?';
        return cp;
    }

    int append_lit( char* dst, int cap, int len, const char* lit ) noexcept
    {
        for ( int i = 0; lit[i] != '\0' && len < cap - 1; ++i )
            dst[len++] = lit[i];
        return len;
    }

    int append_int( char* dst, int cap, int len, int val ) noexcept
    {
        uint32_t mag = 0;
        if ( val < 0 )
        {
            if ( len < cap - 1 )
                dst[len++] = '-';
            mag = static_cast<uint32_t>( -( val + 1 ) ) + 1u;
        }
        else
        {
            mag = static_cast<uint32_t>( val );
        }
        char rev[12] {};
        int nd = 0;
        do
        {
            rev[nd++] = static_cast<char>( '0' + ( mag % 10u ) );
            mag /= 10u;
        } while ( mag > 0u && nd < 12 );
        while ( nd > 0 && len < cap - 1 )
            dst[len++] = rev[--nd];
        return len;
    }

