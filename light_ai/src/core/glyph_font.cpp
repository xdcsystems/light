const uint8_t* glyph_alpha( int idx ) noexcept
{
    if ( idx < 0 || idx >= kSlotCount )
        return kGlyphs['?' - 0x20 + 1];
    return kGlyphs[idx];
}

int glyph_index( uint32_t cp ) noexcept
{
    if ( cp >= 0x20u && cp <= 0x7Eu )
        return static_cast<int>( cp - 0x20u ) + 1;
    if ( cp >= 0x0410u && cp <= 0x042Fu )
        return 96 + static_cast<int>( cp - 0x0410u );
    if ( cp >= 0x0430u && cp <= 0x044Fu )
        return 128 + static_cast<int>( cp - 0x0430u );
    if ( cp == 0x0401u )
        return 160;
    if ( cp == 0x0451u )
        return 161;
    return ( '?' - 0x20 ) + 1;
}

uint32_t next_utf8( const char* str, int len, int& pos ) noexcept
{
    if ( !str || pos < 0 || pos >= len )
        return 0;
    const uint8_t b0 = static_cast<uint8_t>( str[pos] );
    if ( b0 < 0x80u )
    {
        ++pos;
        return sanitize_cp( b0 );
    }
    if ( ( b0 & 0xE0u ) == 0xC0u && pos + 1 < len && is_cont( static_cast<uint8_t>( str[pos + 1] ) ) )
    {
        const uint32_t cp = ( static_cast<uint32_t>( b0 & 0x1Fu ) << 6 ) |
                            static_cast<uint32_t>( static_cast<uint8_t>( str[pos + 1] ) & 0x3Fu );
        pos += 2;
        return ( cp >= 0x80u ) ? sanitize_cp( cp ) : '?';
    }
    if ( ( b0 & 0xF0u ) == 0xE0u && pos + 2 < len &&
         is_cont( static_cast<uint8_t>( str[pos + 1] ) ) && is_cont( static_cast<uint8_t>( str[pos + 2] ) ) )
    {
        const uint32_t b1 = static_cast<uint8_t>( str[pos + 1] ) & 0x3Fu;
        const uint32_t b2 = static_cast<uint8_t>( str[pos + 2] ) & 0x3Fu;
        const uint32_t cp = ( static_cast<uint32_t>( b0 & 0x0Fu ) << 12 ) | ( b1 << 6 ) | b2;
        pos += 3;
        const bool bad = cp < 0x800u || ( cp >= 0xD800u && cp <= 0xDFFFu );
        return bad ? '?' : sanitize_cp( cp );
    }
    if ( ( b0 & 0xF8u ) == 0xF0u && pos + 3 < len &&
         is_cont( static_cast<uint8_t>( str[pos + 1] ) ) &&
         is_cont( static_cast<uint8_t>( str[pos + 2] ) ) &&
         is_cont( static_cast<uint8_t>( str[pos + 3] ) ) )
    {
        const uint32_t b1 = static_cast<uint8_t>( str[pos + 1] ) & 0x3Fu;
        const uint32_t b2 = static_cast<uint8_t>( str[pos + 2] ) & 0x3Fu;
        const uint32_t b3 = static_cast<uint8_t>( str[pos + 3] ) & 0x3Fu;
        const uint32_t cp = ( static_cast<uint32_t>( b0 & 0x07u ) << 18 ) | ( b1 << 12 ) | ( b2 << 6 ) | b3;
        pos += 4;
        return ( cp >= 0x10000u && cp <= 0x10FFFFu ) ? sanitize_cp( cp ) : '?';
    }
    ++pos;
    return '?';
}

int text_len( std::string_view text ) noexcept
{
    const int bytes = static_cast<int>( text.size() );
    int pos = 0;
    int count = 0;
    while ( pos < bytes )
    {
        if ( next_utf8( text.data(), bytes, pos ) != 0 )
            ++count;
    }
    return count;
}

void build_atlas( std::array<uint8_t, kAtlasBytes>& atlas ) noexcept
{
    atlas.fill( 0 );
    fill_solid_cell( atlas );
    for ( int idx = 1; idx < kSlotCount; ++idx )
    {
        const int cell_x = ( idx % kAtlasCols ) * kCellW + kCellPad;
        const int cell_y = ( idx / kAtlasCols ) * kCellH + kCellPad;
        const uint8_t* alpha = kGlyphs[idx];
        for ( int r = 0; r < kGlyphH; ++r )
        {
            uint8_t* dst = atlas.data() + ( cell_y + r ) * kAtlasW + cell_x;
            const uint8_t* src = alpha + r * kGlyphW;
            std::copy_n( src, static_cast<int>( kGlyphW ), dst );
        }
    }
}

void glyph_uv( int idx, float& u0, float& v0, float& u1, float& v1 ) noexcept
{
    const int safe = std::clamp( idx, 0, kSlotCount - 1 );
    const int col = safe % kAtlasCols;
    const int row = safe / kAtlasCols;
    const float x = static_cast<float>( col * kCellW + kCellPad );
    const float y = static_cast<float>( row * kCellH + kCellPad );
    u0 = x / static_cast<float>( kAtlasW );
    v0 = y / static_cast<float>( kAtlasH );
    u1 = ( x + static_cast<float>( kGlyphW ) ) / static_cast<float>( kAtlasW );
    v1 = ( y + static_cast<float>( kGlyphH ) ) / static_cast<float>( kAtlasH );
}

void solid_uv( float& u, float& v ) noexcept
{
    u = ( static_cast<float>( kCellPad ) + 0.5f * static_cast<float>( kGlyphW ) ) / static_cast<float>( kAtlasW );
    v = ( static_cast<float>( kCellPad ) + 0.5f * static_cast<float>( kGlyphH ) ) / static_cast<float>( kAtlasH );
}

int format_person( char* dst, int dst_cap, int id, bool lang_ru ) noexcept
{
    if ( !dst || dst_cap <= 0 )
        return 0;
    // UTF-8 prefix literals for Russian and English callouts (no heap, no snprintf).
    const char* prefix = lang_ru ? "\xD1\x87\xD0\xB5\xD0\xBB\xD0\xBE\xD0\xB2\xD0\xB5\xD0\xBA " : "person ";
    int len = append_lit( dst, dst_cap, 0, prefix );
    len = append_int( dst, dst_cap, len, id );
    dst[len] = '\0';
    return len;
}

